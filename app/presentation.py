def preview_text(stats: MirrorStats) -> str:
    if not stats.others_scores:
        return (
            "⏳ هنوز کسی به آینه‌ات جواب نداده. "
            "لینک را برای چند نفر بفرست تا اولین نتیجه آماده شود."
        )

    ranked = sorted(
        stats.others_scores.items(),
        key=lambda item: item[1],
        reverse=True,
    )
    top_key, top_score = ranked[0]
    top_percent = round(top_score * 20)

    gaps: list[tuple[float, str, float, float]] = []
    for key, others_score in stats.others_scores.items():
        own_score = stats.self_scores.get(key)
        if own_score is not None:
            gaps.append(
                (abs(others_score - own_score), key, own_score, others_score)
            )

    surprise = ""
    if gaps:
        _, gap_key, own_score, others_score = max(gaps)
        own_percent = round(own_score * 20)
        others_percent = round(others_score * 20)

        if others_score > own_score:
            sentence = (
                "بقیه این ویژگی را بیشتر از چیزی در تو می‌بینند "
                "که خودت درباره خودت فکر می‌کنی."
            )
        elif others_score < own_score:
            sentence = (
                "خودت این ویژگی را بیشتر از چیزی در خودت می‌بینی "
                "که بقیه تا امروز دیده‌اند."
            )
        else:
            sentence = "نظر تو و بقیه درباره این ویژگی تقریباً یکی است."

        surprise = (
            "\n\n🤯 <b>جالب‌ترین تفاوت تا اینجا</b>\n"
            f"{TRAIT_BY_KEY[gap_key].title}: "
            f"خودت <b>{own_percent}٪</b> | "
            f"دیگران <b>{others_percent}٪</b>\n"
            f"{sentence}"
        )

    return (
        "👀 <b>پیش‌نمایش رایگان آینه‌ات</b>\n"
        f"این نتیجه فعلاً بر اساس <b>{stats.respondent_count} پاسخ ناشناس</b> "
        "آماده شده.\n\n"
        "✨ <b>ویژگی‌ای که بیشتر از همه به چشم آمده</b>\n"
        f"{TRAIT_BY_KEY[top_key].title} — <b>{top_percent}٪</b>"
        f"{surprise}\n\n"
        "🔒 <b>در گزارش کامل چه می‌گیری؟</b>\n"
        "• جمع‌بندی شخصی‌سازی‌شده و مفصل\n"
        "• توضیح سه ویژگی اصلی با معنی کاربردی آن‌ها\n"
        "• غافلگیری مثبت و مهم‌ترین اختلاف نظر\n"
        "• بخشی که نظر تو و بقیه در آن نزدیک است\n"
        "• بررسی جداگانه هر ۸ ویژگی\n"
        "• چند پیشنهاد عملی متناسب با نتیجه خودت\n"
        "• راهنمای استفاده درست از نتیجه‌ها\n\n"
        "این فقط بخش کوچکی از آینه‌اته؛ گزارش کامل با داده‌های واقعی خودت نوشته می‌شه 🪞"
    )
